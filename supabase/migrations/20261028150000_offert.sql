-- Offerter: prislista, artiklar, offerter med rader, inställningar och kundgodkännande via länk.

-- ---------------------------------------------------------------------------
-- Inställningar (t.ex. standardvillkor för offerter)
-- ---------------------------------------------------------------------------
create table app_settings (
  key text primary key,
  value text not null default '',
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Prislista
-- ---------------------------------------------------------------------------
create table article_groups (
  id text primary key,
  name text not null,
  sort_order int not null default 0
);

create table articles (
  id uuid primary key default gen_random_uuid(),
  article_no text,
  name text not null,
  group_id text not null references article_groups (id),
  unit text not null default 'st',
  price numeric(12, 2),            -- pris exkl. moms; null = ej satt
  cost numeric(12, 2) not null default 0,
  vat_rate numeric(5, 2) not null default 25,
  room_id uuid references rooms (id) on delete set null,  -- förslag när lokalen bokas
  description text,
  active boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index on articles (group_id);
create unique index on articles (article_no) where article_no is not null;

-- ---------------------------------------------------------------------------
-- Offerter
-- ---------------------------------------------------------------------------
create type quote_status as enum ('utkast', 'skickad', 'accepterad', 'avbojd');

create table quotes (
  id uuid primary key default gen_random_uuid(),
  number int generated by default as identity (start with 1001) unique,
  title text not null,
  status quote_status not null default 'utkast',
  event_id uuid references events (id) on delete set null,
  company_id uuid references companies (id) on delete set null,
  contact_id uuid references contacts (id) on delete set null,
  salesperson_id uuid references profiles (id) on delete set null,
  valid_until date,
  intro text,
  terms text,
  share_token uuid not null default gen_random_uuid() unique,
  sent_at timestamptz,
  accepted_at timestamptz,
  accepted_name text,
  accepted_email text,
  declined_at timestamptz,
  customer_comment text,
  created_by uuid references profiles (id) default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index on quotes (event_id);
create index on quotes (company_id);
create index on quotes (status);

create type quote_line_kind as enum ('ingar', 'tillval');

create table quote_lines (
  id uuid primary key default gen_random_uuid(),
  quote_id uuid not null references quotes (id) on delete cascade,
  group_id text not null references article_groups (id),
  article_id uuid references articles (id) on delete set null,
  description text not null,
  line_date date,
  quantity numeric(12, 2) not null default 1,
  unit text not null default 'st',
  unit_price numeric(12, 2) not null default 0,
  cost numeric(12, 2) not null default 0,
  discount_pct numeric(5, 2) not null default 0 check (discount_pct between 0 and 100),
  vat_rate numeric(5, 2) not null default 25,
  kind quote_line_kind not null default 'ingar',
  sort_order int not null default 0
);
create index on quote_lines (quote_id);

create trigger quotes_touch before update on quotes for each row execute function touch_updated_at();
create trigger articles_touch before update on articles for each row execute function touch_updated_at();

-- Summor per offert. Rabatt per rad, moms per rad. Tillval räknas separat.
create view quote_overview with (security_invoker = true) as
select
  q.*,
  c.name as company_name,
  ct.name as contact_name,
  e.title as event_title,
  coalesce(sum(round(l.quantity * l.unit_price * (1 - l.discount_pct / 100), 2)) filter (where l.kind = 'ingar'), 0) as total_ex_vat,
  coalesce(sum(round(l.quantity * l.unit_price * (1 - l.discount_pct / 100) * l.vat_rate / 100, 2)) filter (where l.kind = 'ingar'), 0) as total_vat,
  coalesce(sum(round(l.quantity * l.unit_price * (1 - l.discount_pct / 100), 2)) filter (where l.kind = 'tillval'), 0) as addons_ex_vat
from quotes q
left join companies c on c.id = q.company_id
left join contacts ct on ct.id = q.contact_id
left join events e on e.id = q.event_id
left join quote_lines l on l.quote_id = q.id
group by q.id, c.name, ct.name, e.title;

-- ---------------------------------------------------------------------------
-- Kundens sida: läsa och godkänna offerten via delningslänken, utan inloggning.
-- Bara skickade, accepterade eller avböjda offerter syns. Interna fält (kostnad,
-- marginal, interna anteckningar) lämnas aldrig ut.
-- ---------------------------------------------------------------------------
create function public_quote(p_token uuid) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'number', q.number,
    'title', q.title,
    'status', q.status,
    'valid_until', q.valid_until,
    'intro', q.intro,
    'terms', q.terms,
    'sent_at', q.sent_at,
    'accepted_at', q.accepted_at,
    'accepted_name', q.accepted_name,
    'declined_at', q.declined_at,
    'company_name', c.name,
    'contact_name', ct.name,
    'salesperson_name', p.full_name,
    'salesperson_email', p.email,
    'event_title', e.title,
    'bookings', coalesce((
      select jsonb_agg(jsonb_build_object('room', r.name, 'starts_at', b.starts_at, 'ends_at', b.ends_at) order by b.starts_at)
      from bookings b join rooms r on r.id = b.room_id
      where b.event_id = q.event_id
    ), '[]'::jsonb),
    'lines', coalesce((
      select jsonb_agg(jsonb_build_object(
        'group', g.name, 'group_order', g.sort_order, 'description', l.description, 'line_date', l.line_date,
        'quantity', l.quantity, 'unit', l.unit, 'unit_price', l.unit_price,
        'discount_pct', l.discount_pct, 'vat_rate', l.vat_rate, 'kind', l.kind
      ) order by g.sort_order, l.sort_order)
      from quote_lines l join article_groups g on g.id = l.group_id
      where l.quote_id = q.id
    ), '[]'::jsonb)
  )
  from quotes q
  left join companies c on c.id = q.company_id
  left join contacts ct on ct.id = q.contact_id
  left join profiles p on p.id = q.salesperson_id
  left join events e on e.id = q.event_id
  where q.share_token = p_token
    and q.status in ('skickad', 'accepterad', 'avbojd')
$$;

create function respond_to_quote(p_token uuid, p_accept boolean, p_name text, p_email text, p_comment text default null)
returns text
language plpgsql security definer set search_path = public as $$
declare
  q quotes%rowtype;
begin
  select * into q from quotes where share_token = p_token for update;
  if not found or q.status not in ('skickad') then
    return 'ej_tillganglig';
  end if;
  if q.valid_until is not null and q.valid_until < (now() at time zone 'Europe/Stockholm')::date then
    return 'utgangen';
  end if;
  if coalesce(trim(p_name), '') = '' or coalesce(trim(p_email), '') !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    return 'ogiltig';
  end if;

  update quotes set
    status = case when p_accept then 'accepterad'::quote_status else 'avbojd'::quote_status end,
    accepted_at = case when p_accept then now() else null end,
    declined_at = case when p_accept then null else now() end,
    accepted_name = left(trim(p_name), 200),
    accepted_email = left(trim(p_email), 200),
    customer_comment = left(nullif(trim(coalesce(p_comment, '')), ''), 2000)
  where id = q.id;
  return case when p_accept then 'accepterad' else 'avbojd' end;
end $$;

