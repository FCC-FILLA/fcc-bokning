create policy "admin skriver" on app_settings for all to authenticated using (is_admin()) with check (is_admin());
create policy "läs" on article_groups for select to authenticated using (is_member());
create policy "admin skriver" on article_groups for all to authenticated using (is_admin()) with check (is_admin());
create policy "läs" on articles for select to authenticated using (is_member());
create policy "admin skriver" on articles for all to authenticated using (is_admin()) with check (is_admin());
create policy "läs" on quotes for select to authenticated using (is_member());
create policy "bokare skriver" on quotes for all to authenticated using (can_book()) with check (can_book());
create policy "läs" on quote_lines for select to authenticated using (is_member());
create policy "bokare skriver" on quote_lines for all to authenticated using (can_book()) with check (can_book());

grant select, insert, update, delete on app_settings, article_groups, articles, quotes, quote_lines to authenticated;
grant select on quote_overview to authenticated;
revoke execute on all functions in schema public from public, anon;
grant execute on all functions in schema public to authenticated;
revoke execute on function handle_new_user() from authenticated;
